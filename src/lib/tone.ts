const BY_ID = new Map(TONES.map((t) => [t.id, t]));

export const DEFAULT_TONE = TONES[0];

/** id 로 톤을 찾는다. 빈 값이나 모르는 값이면 다큐멘터리톤. */
export function resolveTone(id: string | undefined): Tone {
  const key = (id || '').trim().toLowerCase();
  if (!key || key === 'auto') return DEFAULT_TONE;
  return BY_ID.get(key) ?? DEFAULT_TONE;
}

/** 대본 프롬프트에 넣을 최종 지시문. */
export function buildToneGuide(tone: Tone): string {
  return `${tone.guide} ${TRUTH_GUARD}`;
}
